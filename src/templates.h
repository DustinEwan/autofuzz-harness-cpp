[[noreturn]] inline void fail(const std::string& m) { throw BuildError{m}; }

// Serialize with replacement instead of throwing on invalid UTF-8: target
// strings can hold raw bytes, and a driver must answer, not die.
inline std::string afz_dump(const json& v) {
    return v.dump(-1, ' ', false, json::error_handler_t::replace);
}

// Grow a shared buffer to the count the callee will index with; the engine
// fuzzes each array's length independently, the API promises one shared one.
template <class V>
typename V::value_type* pad_to(V& v, std::size_t n) {
    if (v.size() < n) v.resize(n);
    return v.data();
}

// Bytes (or elements) needed to index by every element of an index vector,
// at least the vector's own length, capped so a fuzzed huge index cannot
// request an absurd allocation.
template <typename T> std::size_t afz_span(const std::vector<T>& v) {
    std::size_t m = v.size();
    for (const T& x : v) {
        long long ll = static_cast<long long>(x);
        if (ll >= 0 && static_cast<std::size_t>(ll) + 1 > m)
            m = static_cast<std::size_t>(ll) + 1;
    }
    return m > (1u << 20) ? (1u << 20) : m;
}
inline std::string show(const json& v) {
    std::string text = afz_dump(v);
    if (text.size() > 120) text = text.substr(0, 120) + "...";
    return text;
}

// Arguments arrive as ValueTree nodes: a scalar is
// `{"node":"number","value":4,"provenance":...}`, an object is
// `{"node":"object","fields":[["name",tree],...]}`, and so on. The readers
// unwrap the node tag and ignore provenance; a raw JSON value of the right
// shape is also accepted, which is what the reproducer script embeds.
// Integers convert totally: a value that does not fit converts with
// static_cast semantics, and a non-finite number maps to 0 / min / max, so a
// type boundary never turns into undefined behavior.
inline const json& node_of(const json& v) {
    if (v.is_object() && v.contains("node") && v["node"].is_string()) {
        const std::string& n = v["node"].get_ref<const std::string&>();
        if (n == "boolean" || n == "number" || n == "bigInt" || n == "string" || n == "literal") {
            if (v.contains("value")) return v.at("value");
        }
    }
    return v;
}

inline const std::string* node_tag(const json& v) {
    if (v.is_object() && v.contains("node") && v["node"].is_string())
        return &v["node"].get_ref<const std::string&>();
    return nullptr;
}

inline bool is_null_node(const json& v) {
    if (v.is_null()) return true;
    const std::string* n = node_tag(v);
    return n && (*n == "null" || *n == "undefined");
}

inline long long i_of(const json& v) {
    const json& x = node_of(v);
    if (x.is_number_integer()) return x.get<long long>();
    if (x.is_number_unsigned()) return static_cast<long long>(x.get<unsigned long long>());
    if (x.is_number_float()) {
        double d = x.get<double>();
        if (d != d) return 0;
        if (d >= 9.2233720368547758e18) return 9223372036854775807LL;
        if (d <= -9.2233720368547758e18) return -9223372036854775807LL - 1;
        return static_cast<long long>(d);
    }
    if (x.is_string()) {
        const std::string& s = x.get_ref<const std::string&>();
        try {
            std::size_t used = 0;
            long long n = std::stoll(s, &used);
            if (used == s.size()) return n;
        } catch (const std::out_of_range&) {
            // A decimal wider than the type saturates, as the float path
            // does; a type boundary stays a value, never a crash.
            return s.find('-') == 0 ? (-9223372036854775807LL - 1) : 9223372036854775807LL;
        } catch (...) {
        }
        try {
            return i_of(json(std::stod(s)));
        } catch (const std::out_of_range&) {
            return s.find('-') == 0 ? (-9223372036854775807LL - 1) : 9223372036854775807LL;
        } catch (...) {
        }
    }
    if (x.is_boolean()) return x.get<bool>() ? 1 : 0;
    fail(show(v) + " is not an integer");
}

inline unsigned long long u_of(const json& v) {
    const json& x = node_of(v);
    if (x.is_number_unsigned()) return x.get<unsigned long long>();
    if (x.is_number_integer()) return static_cast<unsigned long long>(x.get<long long>());
    if (x.is_number_float()) {
        double d = x.get<double>();
        if (d != d) return 0;
        if (d >= 1.8446744073709552e19) return 18446744073709551615ULL;
        if (d <= 0.0) return 0;
        return static_cast<unsigned long long>(d);
    }
    if (x.is_string()) {
        const std::string& s = x.get_ref<const std::string&>();
        try {
            std::size_t used = 0;
            unsigned long long n = std::stoull(s, &used);
            if (used == s.size()) return n;
        } catch (const std::out_of_range&) {
            return s.find('-') == 0 ? 0ULL : 18446744073709551615ULL;
        } catch (...) {
        }
        try {
            return u_of(json(std::stod(s)));
        } catch (const std::out_of_range&) {
            return s.find('-') == 0 ? 0ULL : 18446744073709551615ULL;
        } catch (...) {
        }
    }
    if (x.is_boolean()) return x.get<bool>() ? 1u : 0u;
    fail(show(v) + " is not a non-negative integer");
}

inline bool b_of(const json& v) {
    const json& x = node_of(v);
    if (x.is_boolean()) return x.get<bool>();
    if (x.is_number()) return i_of(x) != 0;
    fail(show(v) + " is not a boolean");
}

// JSON has no token for the non-finite values; the wire carries them by name
// ("nan", "infinity", "negativeInfinity", matching the engine's SpecialNumber).
inline double f_of(const json& v) {
    const json& x = node_of(v);
    if (x.is_number()) return x.get<double>();
    if (x.is_string()) {
        const std::string& s = x.get_ref<const std::string&>();
        if (s == "nan" || s == "NaN" || s == "naN") return 0.0 / 0.0;
        if (s == "infinity" || s == "Infinity" || s == "inf") return 1.0 / 0.0;
        if (s == "negativeInfinity" || s == "-infinity" || s == "-Infinity") return -1.0 / 0.0;
        try {
            return std::stod(s);
        } catch (...) {
        }
    }
    if (x.is_boolean()) return x.get<bool>() ? 1.0 : 0.0;
    fail(show(v) + " is not a number");
}

inline std::string s_of(const json& v) {
    const json& x = node_of(v);
    if (x.is_string()) return x.get<std::string>();
    fail(show(v) + " is not a string");
}

inline std::vector<std::uint8_t> bytes_of(const json& v) {
    const std::string* n = node_tag(v);
    if (n && *n == "buffer" && v.contains("bytes") && v["bytes"].is_array()) {
        std::vector<std::uint8_t> out;
        for (const auto& b : v["bytes"]) out.push_back(static_cast<std::uint8_t>(u_of(b)));
        return out;
    }
    if (n && *n == "string" && v.contains("value") && v["value"].is_string()) {
        const std::string& s = v["value"].get_ref<const std::string&>();
        return std::vector<std::uint8_t>(s.begin(), s.end());
    }
    if (v.is_array()) {
        std::vector<std::uint8_t> out;
        for (const auto& b : v) out.push_back(static_cast<std::uint8_t>(u_of(b)));
        return out;
    }
    fail(show(v) + " is not a buffer");
}

inline const json& obj_of(const json& v) {
    const std::string* n = node_tag(v);
    if (!n || *n != "object" || !v.contains("fields") || !v["fields"].is_array())
        fail(show(v) + " is not an object value");
    return v;
}

inline const json& field(const json& o, const char* name) {
    for (const auto& f : o.at("fields"))
        if (f.is_array() && f.size() == 2 && f[0].is_string() &&
            f[0].get_ref<const std::string&>() == name)
            return f[1];
    fail("the object value has no field " + std::string(name));
}

inline const json null_json;

inline const json& field_or_null(const json& o, const char* name) {
    if (!o.is_object() || !o.contains("fields") || !o["fields"].is_array()) return null_json;
    for (const auto& f : o.at("fields"))
        if (f.is_array() && f.size() == 2 && f[0].is_string() &&
            f[0].get_ref<const std::string&>() == name)
            return f[1];
    return null_json;
}

inline std::vector<json> arr_of(const json& v) {
    if (v.is_object() && v.contains("items") && v["items"].is_array())
        return v["items"].get<std::vector<json>>();
    if (v.is_array()) return v.get<std::vector<json>>();
    fail(show(v) + " is not a sequence value");
}

inline std::vector<std::pair<json, json>> entries_of(const json& v) {
    if (!v.is_object() || !v.contains("entries") || !v["entries"].is_array())
        fail(show(v) + " is not a map value");
    std::vector<std::pair<json, json>> out;
    for (const auto& e : v["entries"]) {
        if (!e.is_array() || e.size() != 2) fail(show(e) + " is not a [key, value] pair");
        out.emplace_back(e[0], e[1]);
    }
    return out;
}

