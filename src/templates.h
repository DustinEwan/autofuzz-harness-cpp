// Write one line to fd 3; when fd 3 is gone (a target that closed it), fall
// back to stdout as the last line, which is what the plugin reads second.
void write_result(const std::string& line) {
    std::string data = line;
    data += '\n';
    ssize_t n = ::write(3, data.data(), data.size());
    if (n > 0) return;
    ::fwrite(data.data(), 1, data.size(), stdout);
    ::fflush(stdout);
}

void write_result_raw(const char* begin, std::size_t len) {
    ssize_t n = ::write(3, begin, len);
    if (n > 0) return;
    ::fwrite(begin, 1, len, stdout);
    ::fflush(stdout);
}

void append_u64(char* buf, std::size_t cap, std::size_t& at, unsigned long long v) {
    char tmp[24];
    int n = __builtin_snprintf(tmp, sizeof tmp, "%llu", v);
    if (n > 0 && at + static_cast<std::size_t>(n) < cap) {
        std::memcpy(buf + at, tmp, static_cast<std::size_t>(n));
        at += static_cast<std::size_t>(n);
    }
}

void on_crash(int sig) {
    void* frames[24];
    int n = backtrace(frames, 24);
    char buf[1024];
    std::size_t at = 0;
    const char* head = "{\"status\":\"crash\",\"signal\":";
    while (*head && at + 1 < sizeof buf) buf[at++] = *head++;
    append_u64(buf, sizeof buf, at, static_cast<unsigned long long>(sig));
    const char* mid = ",\"frames\":[";
    while (*mid && at + 1 < sizeof buf) buf[at++] = *mid++;
    // The first two frames are the handler and the signal trampoline.
    for (int i = 2; i < n && i < 10; ++i) {
        if (i > 2) {
            if (at + 1 < sizeof buf) buf[at++] = ',';
        }
        char addr[32];
        int an = __builtin_snprintf(addr, sizeof addr, "0x%llx",
                                    static_cast<unsigned long long>(reinterpret_cast<unsigned long>(frames[i])));
        for (int j = 0; j < an && at + 1 < sizeof buf; ++j) buf[at++] = addr[j];
    }
    if (at + 3 < sizeof buf) {
        buf[at++] = ']';
        buf[at++] = '}';
        buf[at++] = '\n';
    }
    write_result_raw(buf, at);
    _exit(128 + sig);
}

bool sanitizer_owns_signals() {
#if defined(__SANITIZE_ADDRESS__)
    return true;
#else
#if defined(__has_feature)
#if __has_feature(address_sanitizer)
    return true;
#endif
#endif
    return false;
#endif
}

void install_crash_handlers() {
    if (sanitizer_owns_signals()) return;
    void* warm[4];
    backtrace(warm, 4); // load the unwind data before a handler needs it
    struct sigaction sa{};
    sa.sa_handler = on_crash;
    sigemptyset(&sa.sa_mask);
    sa.sa_flags = SA_RESETHAND;
    for (int sig : {SIGSEGV, SIGABRT, SIGFPE, SIGILL, SIGBUS}) sigaction(sig, &sa, nullptr);
}

std::string current_exception_type() {
    const std::type_info* t = abi::__cxa_current_exception_type();
    if (!t) return "unknown-exception";
    int status = 0;
    char* dem = abi::__cxa_demangle(t->name(), nullptr, nullptr, &status);
    if (!dem || status != 0) {
        std::free(dem);
        return t->name();
    }
    std::string out(dem);
    std::free(dem);
    return out;
}

