// The stub factories take the function type itself: `stub_function<int(int)>`
// and `Stub<int(int)>`, which is what the code generator has from the lowered
// signature.
template <class F>
struct StubFn;
template <class R, class... A>
struct StubFn<R(A...)> {
    static std::function<R(A...)> make(const json& v) {
        std::string behavior = stub_behavior(v);
        if (behavior == "throw")
            return [](A...) -> R { throw std::runtime_error("afz: stub callback invoked"); };
        if (behavior == "captureArguments")
            return [](A...) -> R {
                g_callbacks.push_back("afz: callback invoked");
                if constexpr (!std::is_void_v<R>) return R{};
            };
        return [](A...) -> R {
            if constexpr (!std::is_void_v<R>) return R{};
        };
    }
};

template <class F>
std::function<F> stub_function(const json& v) {
    return StubFn<F>::make(v);
}

// The same three behaviors for a raw function-pointer parameter: the
// conversion operator hands out a captureless function pointer.
template <class F>
struct Stub;
template <class R, class... A>
struct Stub<R(A...)> {
    std::string behavior = "returnFirst";
    static R first(A...) {
        if constexpr (!std::is_void_v<R>) return R{};
    }
    static R thrower(A...) { throw std::runtime_error("afz: stub callback invoked"); }
    static R capture(A...) {
        g_callbacks.push_back("afz: callback invoked");
        if constexpr (!std::is_void_v<R>) return R{};
    }
    using FnPtr = R (*)(A...);
    operator FnPtr() const {
        if (behavior == "throw") return +thrower;
        if (behavior == "captureArguments") return +capture;
        return +first;
    }
};

